let stream_exe_print_context_expiry () =
  List.iter
    (fun source ->
      let report = Output.run ~mode:Preprocessor.Jit source in
      let error = Output.fault "HCIRVM0027" report in
      Alcotest.(check bool)
        "inactive calls name their parser context" true
        (String.ends_with ~suffix:"requires an active #exe parser context"
           error.message);
      Alcotest.(check bool)
        "inactive calls finish formatting first" true
        (integer_program_report_output_work report > 0))
    [
      {|extern I64 StreamExePrint(U8 *fmt,...);StreamExePrint("40+2;");#exe {}|};
      {|#exe {I64 F(){return StreamExePrint("40+2;");}}F();|};
      {|#exe {I64 (*p)(U8 *fmt,...)=&StreamExePrint;}p("40+2;");|};
      {|#exe {I64 F(I64 (*p)(U8 *fmt,...)=&StreamExePrint){return p("40+2;");}}F();|};
      {|#exe {I64 F(){return StreamExePrint("40+2;");}}#exe {StreamPrint("0;");}F();|};
      {|#exe {I64 (*p)(U8 *fmt,...)=&StreamExePrint;p("I64 F(){return p(\"40+2;\");}F();");}|};
    ];
  List.iter
    (fun mode ->
      let report =
        Output.run ~mode
          {|#exe {StreamExePrint("StreamExePrint(\"40+2;\");");}|}
      in
      ignore (Output.fault "HCIRVM0027" report);
      let malformed =
        Output.run ~mode {|#exe {StreamExePrint("StreamExePrint(\"%%d\");");}|}
      in
      ignore (Output.fault "HCIRVM0025" malformed))
    G.modes

let stream_exe_print_declaration_limits () =
  List.iter
    (fun mode ->
      List.iter
        (fun (_, source) ->
          let measured = Output.run ~mode source in
          ignore (Output.expect "" measured);
          let progress =
            Option.get (integer_program_report_progress measured)
          in
          let steps = progress.runtime.executed_steps in
          let work = integer_program_report_output_work measured in
          let preparation =
            integer_program_report_preparation_work measured |> Option.get
          in
          ignore
            (Output.run ~mode ~max_steps:steps ~max_output_work:work
               ~max_initializer_steps:(max 1 preparation) source
            |> Output.expect "");
          ignore
            (Output.run ~mode ~max_steps:(steps - 1) source
            |> Output.fault "HCIRVM0007");
          ignore
            (Output.run ~mode ~max_output_work:(work - 1) source
            |> Output.fault "HCIRVM0023");
          if preparation > 1 then
            ignore
              (Output.run ~mode ~max_initializer_steps:(preparation - 1) source
              |> Output.fault "HCIRVM0007"))
        stream_exe_print_contexts)
    G.modes

