let expect ?(modes = G.modes) value source () =
  List.iter
    (fun mode ->
      ignore (Output.run ~mode source |> Output.expect ~value:(Some value) ""))
    modes

let stream_exe_print_bridge () =
  ignore
    (Output.run ~mode:Preprocessor.Aot
       {|#exe {I64 N=StreamExePrint("40+2;");StreamPrint("%d;",N);}|}
    |> Output.expect ~value:(Some 42L) "");
  ignore
    (Output.run ~mode:Preprocessor.Jit
       {|#exe {I64 F(){return 40;}}#exe {I64 F(){return 42;}I64 N=StreamExePrint("F();");StreamPrint("%d;",N);}|}
    |> Output.expect ~value:(Some 42L) "");
  ignore
    (Output.run ~mode:Preprocessor.Aot
       {|#exe {I64 N=StreamExePrint("#exe {I64 N=StreamExePrint(\"40+2;\");StreamPrint(\"%%d;\",N);}");StreamPrint("%d;",N);}|}
    |> Output.expect ~value:(Some 42L) "");
  ignore
    (Output.run ~mode:Preprocessor.Jit
       {|#exe {StreamExePrint("I64 Generated(){return 42;}");}#exe {StreamPrint("%d;",Generated());}|}
    |> Output.expect ~value:(Some 42L) "");
  let failed =
    Output.run ~mode:Preprocessor.Aot
      {|#exe {StreamExePrint("Print(\"A\");1/0;");}|}
  in
  ignore (Output.fault ~output:"A" "HCIRVM0009" failed);
  let failed_progress = Option.get (integer_program_report_progress failed) in
  Alcotest.(check int)
    "failed StreamExePrint does not publish generated bytes" 0
    failed_progress.runtime.generated_bytes;
  let malformed =
    Output.run ~mode:Preprocessor.Aot {|#exe {StreamExePrint("%d");}|}
  in
  let malformed = Output.fault "HCIRVM0025" malformed in
  Alcotest.(check bool)
    "StreamExePrint formatting diagnostics name the provider" true
    (String.starts_with ~prefix:"StreamExePrint " malformed.message);
  ignore
    (Output.run ~mode:Preprocessor.Jit
       {|#exe {I64 N=StreamExePrint("%d;",40+2);StreamPrint("%d;",N);}|}
    |> Output.expect ~value:(Some 42L) "");
  let report =
    Output.run ~mode:Preprocessor.Jit
      {|#exe {StreamExePrint("StreamExePrint(\"42;\");");}|}
  in
  ignore (Output.fault "HCIRVM0027" report);
  let progress = Option.get (integer_program_report_progress report) in
  Alcotest.(check bool)
    "nested context check follows bounded formatting" true
    (progress.runtime.output_work > 0);
  Alcotest.(check int)
    "failed nested source does not publish generated bytes" 0
    progress.runtime.generated_bytes

let stream_exe_print_limits () =
  List.iter
    (fun mode ->
      let source =
        {|#exe {I64 N=StreamExePrint("40+2;");StreamPrint("%d;",N);}|}
      in
      let measured = Output.run ~mode source in
      ignore (Output.expect ~value:(Some 42L) "" measured);
      let progress = Option.get (integer_program_report_progress measured) in
      let steps = progress.runtime.executed_steps in
      let work = integer_program_report_output_work measured in
      ignore
        (Output.run ~mode ~max_steps:steps ~max_output_work:work source
        |> Output.expect ~value:(Some 42L) "");
      ignore
        (Output.run ~mode ~max_steps:(steps - 1) source
        |> Output.fault "HCIRVM0007");
      ignore
        (Output.run ~mode ~max_output_work:(work - 1) source
        |> Output.fault "HCIRVM0023");
      let nested =
        {|#exe {StreamExePrint("I64 F(){I64 X=42;return X;}F();");}|}
      in
      ignore
        (Output.run ~mode ~max_frame_bytes:24 ~max_call_depth:2 nested
        |> Output.expect ~value:None "");
      ignore
        (Output.run ~mode ~max_frame_bytes:23 ~max_call_depth:2 nested
        |> Output.fault "HCIRVM0011");
      ignore
        (Output.run ~mode ~max_frame_bytes:24 ~max_call_depth:1 nested
        |> Output.fault "HCIRVM0015"))
    G.modes

